/** Texto na fonte minúscula como máscara '#'. */
export function tinyText(text: string): Sprite {
  const rows = ['', '', '', '', '']
  for (const raw of text) {
    const g = TINY[raw.toUpperCase()] ?? TINY[' ']
    g.forEach((line, i) => (rows[i] += line + '.'))
  }
  return rows.map((r) => r.slice(0, -1))
}

